export function getBriefingByPillar(pillar: string): HumanBrainBriefing {
  const found = HUMAN_BRAIN_BRIEFINGS.find((b) => b.pillar === pillar);
  return found || HUMAN_BRAIN_BRIEFINGS[0];
}

export function getTodaysHumanBriefing(): HumanBrainBriefing {
  const dayIndex = new Date().getDay(); // 0-6
  return HUMAN_BRAIN_BRIEFINGS[dayIndex % HUMAN_BRAIN_BRIEFINGS.length];
}
