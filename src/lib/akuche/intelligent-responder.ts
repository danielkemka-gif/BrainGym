/**
 * AKUCHE FIVE-STAGE SOCRATIC REASONING & FALLBACK ENGINE
 *
 * Implements:
 * 1. The Five-Stage Socratic Reasoning Framework:
 *    - Stage 1: UNDERSTAND (Clarify before advising; single most important question; no premature action plan)
 *    - Stage 2: INVESTIGATE (Go beneath symptoms to root causes; progressive follow-up questioning)
 *    - Stage 3: CHALLENGE (Examine assumptions, confirmation bias, overconfidence, alternative perspectives)
 *    - Stage 4: REASON (Evaluate realistic options, trade-offs, short/long-term consequences, transparency)
 *    - Stage 5: DEVELOP (Translate reasoned conclusion into grounded, non-arbitrary next steps & review points)
 * 2. Multi-Turn Conversation History Awareness (Phase 6):
 *    - Reads prior user and assistant turns so follow-up messages progress naturally and never repeat templates.
 * 3. Reasoning Transparency & Honest Fallback Attribution (Phase 2 & Phase 6):
 *    - Explicitly tags responses generated by the fallback engine (`isFallback: true`) and communicates
 *      what information is being used, what remains uncertain, and what would change a recommendation.
 */

import {
  AkucheInteractionMode,
  AkucheQueryClassification,
  classifyUserQuery,
  detectPromptInjectionAttempt,
} from "./master-intelligence";
import { ClientSuppliedContext, ServerUserProfile } from "./context-engine";
import { AkucheClaritySnapshot, retrieveRelevantMemories } from "./memory-engine";

export interface SocraticThinkingCards {
  type: "factual" | "guided_thinking" | "action_mission" | "decision_matrix";
  directAnswer?: string;
  whatWeKnow?: string[];
  whatWeDontKnow?: string[];
  assumptions?: string[];
  risks?: string[];
  options?: string[];
  questionsToInvestigate?: string[];
  nextQuestion?: string;
  mission?: {
    title: string;
    deadline: string;
    steps: string[];
    whyItMatters?: string;
    howToDoIt?: string;
    doneWhen?: string;
  };
}

export interface AkucheIntelligentResponse {
  text: string;
  cards: SocraticThinkingCards | null;
  claritySnapshot: Omit<AkucheClaritySnapshot, "id" | "updatedAt"> | null;
  thinkingMirrorObservation?: {
    patternName: string;
    type: "strength" | "blind_spot" | "habit";
    observation: string;
    selfAwarenessPrompt: string;
  } | null;
  classification: AkucheQueryClassification;
  isFallback: boolean;
}

export function generateContextualIntelligentResponse(params: {
  message: string;
  history?: { role: string; content: string }[];
  mode?: AkucheInteractionMode;
  serverProfile?: ServerUserProfile | null;
  clientContext?: ClientSuppliedContext | null;
}): AkucheIntelligentResponse {
  const {
    message,
    history = [],
    mode = "coaching_chat",
    serverProfile,
    clientContext,
  } = params;

  const trimmed = (message || "").trim();
  const q = trimmed.toLowerCase();
  const classification = classifyUserQuery(trimmed, mode, history);

  // 1. Guard against prompt injection attempts
  if (detectPromptInjectionAttempt(trimmed)) {
    return {
      text: `I am **Akuche**, your personal thinking and decision-making coach. My role is to help you think clearly, examine assumptions, weigh trade-offs, and make sound decisions across business, career, relationships, and everyday life.\n\nWhat real-world situation, challenge, or decision would you like us to think through together right now?`,
      cards: null,
      claritySnapshot: null,
      thinkingMirrorObservation: null,
      classification,
      isFallback: true,
    };
  }

  // Gather relevant user context for Reasoning Transparency
  const memoryEnabled = clientContext?.memoryEnabled !== false;
  const relevantMemories =
    memoryEnabled && clientContext?.memories
      ? retrieveRelevantMemories(trimmed, clientContext.memories, 4)
      : [];
  const recentDecisions =
    memoryEnabled && clientContext?.recentDecisions
      ? clientContext.recentDecisions.slice(0, 2)
      : [];
  const userName =
    serverProfile?.name || clientContext?.profileOverride?.name || "";

  // 2. Greeting / Onboarding
  if (classification.intent === "greeting_onboarding") {
    const greetingName = userName ? `, ${userName}` : "";
    return {
      text: `Hello${greetingName}. I am **Akuche** — your thinking and decision-development partner.\n\nInstead of handing you generic advice or premature checklists, I help you **understand** what is really happening, **investigate** root causes, **challenge** hidden assumptions, **reason** through your options, and **develop** sound decisions.\n\nWhat situation, decision, or challenge is on your mind today?`,
      cards: null,
      claritySnapshot: null,
      thinkingMirrorObservation: null,
      classification,
      isFallback: true,
    };
  }

  // 3. Simple Factual / Conceptual Questions (Direct Response without unnecessary questioning)
  if (classification.intent === "simple_factual") {
    return buildSimpleFactualResponse(trimmed, q, classification);
  }

  // 4. Explicit Deliverable Creation Requests
  if (classification.intent === "deliverable_creation") {
    return buildDeliverableResponse(trimmed, q, classification);
  }

  // 5. FIVE-STAGE SOCRATIC REASONING PROGRESSION
  switch (classification.reasoningStage) {
    case "stage_1_understand":
      return buildStage1UnderstandResponse({
        message: trimmed,
        q,
        classification,
        relevantMemories,
        recentDecisions,
      });

    case "stage_2_investigate":
      return buildStage2InvestigateResponse({
        message: trimmed,
        q,
        history,
        classification,
        relevantMemories,
      });

    case "stage_3_challenge":
      return buildStage3ChallengeResponse({
        message: trimmed,
        q,
        history,
        mode,
        classification,
        relevantMemories,
      });

    case "stage_4_reason":
      return buildStage4ReasonResponse({
        message: trimmed,
        q,
        history,
        classification,
        relevantMemories,
        recentDecisions,
      });

    case "stage_5_develop":
    default:
      return buildStage5DevelopResponse({
        message: trimmed,
        q,
        history,
        classification,
        relevantMemories,
        recentDecisions,
      });
  }
}

